export function getAttendance(semester: number): Attendance[] {
  const data = semesters[semester];
  if (data.attendance) return data.attendance;

  if (data.subjects.length > 0) {
    return data.subjects.map((subject, index) => {
      const hours = subject.hours === 0 ? 0 : subject.hours <= 72 ? 16 : subject.hours >= 180 ? 32 : 24;
      const firstMissed = hours === 0 ? 0 : [0, 2, 4, 0, 6, 2, 0, 4, 0][index % 9];
      const secondMissed = hours === 0 ? 0 : [2, 0, 4, 2, 0, 4, 0, 2, 0][index % 9];
      return absence(subject.title, firstMissed, hours, secondMissed, hours);
    });
  }

  return data.attestation.map((row) => absence(row.title, 0, 0, 0, 0));
}

export function getProgressSubjects(semester: number): string[] {
  const data = semesters[semester];
  if (data.progressSubjects) return data.progressSubjects;
  return getAttendance(semester).map((row) => row.title);
}

export type ControlEvent = {
  name: string;
  held: string;
  points: number | string;
  posted: string;
  max: number | string;
  isSummary?: boolean;
};

const fifthSemesterWithPoints = new Set([
  "Основы права",
  "Управление данными",
  "Бизнес-инжиниринг",
]);

export function getControlEvents(semester: number, title: string, index: number): ControlEvent[] {
  if (semester === 5) {
    if (fifthSemesterWithPoints.has(title)) {
      return [
        { name: "Контрольная точка 1", held: "-", points: "", posted: "-", max: "", isSummary: true },
        { name: "Контрольная точка 2", held: "-", points: "", posted: "-", max: "", isSummary: true },
      ];
    }
    return [];
  }

  if (semester === 4 && title === "Учебный проект") {
    return [
      { name: "Рубежный контроль", held: "09.04.2026", points: 70, posted: "25.06.2026", max: 100 },
      { name: "Контрольная точка 1", held: "-", points: 70, posted: "-", max: 100, isSummary: true },
      { name: "Контрольная точка 2", held: "-", points: 70, posted: "-", max: 100, isSummary: true },
    ];
  }

  const subject = semesters[semester].subjects.find((item) => item.title === title);
  const points = subject?.points ?? 0;
  const year = ["", "2024", "2025", "2025", "2026", "2026"][semester];
  const month = semester % 2 === 0 ? "04" : "11";
  const day = String(10 + (index % 15)).padStart(2, "0");

  return [
    { name: "Рубежный контроль", held: `${day}.${month}.${year}`, points: Math.max(0, Math.round(points * 0.32)), posted: `${day}.${month}.${year}`, max: 30 },
    { name: "Контрольная точка 1", held: `${day}.${month}.${year}`, points: Math.max(0, Math.round(points * 0.63)), posted: `${day}.${month}.${year}`, max: 60, isSummary: true },
    { name: "Контрольная точка 2", held: subject?.date ?? "-", points, posted: subject?.date ?? "-", max: 100, isSummary: true },
  ];
}