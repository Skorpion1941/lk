const gradeRow = (
  title: string,
  assessment: string,
  hours: number,
  credits: number,
  points: number,
  letter: string,
  grade: string,
  date: string,
): Subject => ({ title, assessment, hours, credits, points, letter, grade, date });

const attRow = (
  title: string,
  assessment = "",
  kt1: string | number = "",
  kt2: string | number = "",
  kt1Max: string | number = "",
  kt2Max: string | number = "",
  pa: string | number = "",
  paMax: string | number = "",
  total: string | number = "",
  totalMax: string | number = "",
): AttestationRow => ({
  title,
  assessment,
  kt1,
  kt2,
  kt1Max,
  kt2Max,
  pa,
  paMax,
  total,
  totalMax,
});

const absence = (
  title: string,
  firstMissed: number,
  firstHours: number,
  secondMissed: number,
  secondHours: number,
): Attendance => ({
  title,
  firstMissed,
  firstHours,
  secondMissed,
  secondHours,
});

